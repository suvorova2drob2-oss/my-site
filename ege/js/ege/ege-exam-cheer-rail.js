  function update(root, st, opts) {
    if (!root) return;
    opts = opts || {};
    var textEl = root.querySelector("#ege-gx-cheer-text");
    var tagEl = root.querySelector("#ege-gx-cheer-tag");
    if (!textEl) return;

    st = st || {};
    var bucket = bucketFor(st);
    var prevBucket = root.getAttribute("data-cheer-bucket") || "";
    var force = !!opts.force;
    var next;

    if (force || bucket !== prevBucket) {
      root.setAttribute("data-cheer-bucket", bucket);
      var prev = textEl.textContent || "";
      next = phraseFor(st, prev);
      textEl.textContent = next.text;
      if (tagEl) tagEl.textContent = next.tag || "";
    } else {
      next = {
        text: textEl.textContent || "",
        tag: tagEl ? tagEl.textContent || "" : "",
        voice: root.classList.contains("ege-gx-cheer--legend-tyson")
          ? "tyson"
          : root.classList.contains("ege-gx-cheer--legend-jobs")
            ? "jobs"
            : root.classList.contains("ege-gx-cheer--heart")
              ? "heart"
              : ""
      };
    }

    applyCheerClasses(root, st, next);
  }

