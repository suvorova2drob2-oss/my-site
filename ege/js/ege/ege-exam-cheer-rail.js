  function listeningTag(st) {
    if (st && st.context === "listening-tfns") return "+/−/? · слух";
    if (st && st.context === "listening-mc") return "1/2/3 · слух";
    if (st && st.context === "listening") return "главное — слух";
    return "";
  }

  function pickEntry(arr, prev) {
    if (!arr || !arr.length) return { text: "", tag: "", voice: "" };
    var item = arr[Math.floor(Math.random() * arr.length)];
    if (typeof item === "string") {
      return { text: pickAvoidRepeat(arr, prev), tag: "", voice: "" };
    }
    var guard = 0;
    while (item && item.text === prev && guard < 10) {
      item = arr[Math.floor(Math.random() * arr.length)];
      guard++;
    }
    return item || { text: "", tag: "", voice: "" };
  }

  function pickRebuild(st, prevText) {
    var P = poolFor(st);
    var pct = st.percent != null ? st.percent : 0;
    var r = Math.random();
    if (r < 0.44 && P.rebuildHeart.length) {
      return pickEntry(P.rebuildHeart, prevText);
    }
    if ((pct < 40 || r < 0.78) && P.rebuildLegend.length) {
      return pickEntry(P.rebuildLegend, prevText);
    }
    return {
      text: pickAvoidRepeat(P.rebuild, prevText),
      tag: st.context === "listening-tfns" || st.context === "listening-mc" || st.context === "listening" ? listeningTag(st) : st.context === "reading" ? "читать — круто" : "ещё один шаг",
      voice: ""
    };
  }

  function pick(arr) {
    if (!arr || !arr.length) return "";
    return arr[Math.floor(Math.random() * arr.length)];
  }

  function pickAvoidRepeat(arr, prev) {
    if (!arr || !arr.length) return "";
    if (arr.length === 1) return arr[0];
    var t = pick(arr);
    var guard = 0;
    while (t === prev && guard < 8) {
      t = pick(arr);
      guard++;
    }
    return t;
  }

  /**
   * Стабильный «ярус» — меняем текст только при смене яруса, не на каждый символ в поле.
   */
  function bucketFor(st) {
    st = st || {};
    var phase = st.phase || "welcome";
    var filled = st.filled | 0;
    var total = st.total | 0;
    var pct = st.percent != null ? st.percent : -1;

    if (phase === "welcome") return "welcome";
    if (phase === "checked") {
      if (pct >= 100) return "checked:100";
      if (pct >= 80) return "checked:80";
      if (pct >= 60) return "checked:60";
      return "checked:low";
    }
    if (total <= 0) return "working:steady";
    if (filled >= total) return "working:full";
    if (filled >= total - 1 && filled > 0) return "working:almost";
    if (filled >= Math.ceil(total / 2)) return "working:half";
    if (filled > 0) return "working:few";
    return "working:steady";
  }

  /**
   * @param {{ phase?: string, filled?: number, total?: number, percent?: number }} st
   * @param {string} prevText
   */
  function phraseFor(st, prevText) {
    st = st || {};
    var P = poolFor(st);
    var phase = st.phase || "welcome";
    var filled = st.filled | 0;
    var total = st.total | 0;
    var pct = st.percent != null ? st.percent : 0;
    var tag =
      st.context === "listening-tfns" || st.context === "listening-mc" || st.context === "listening"
        ? listeningTag(st)
        : st.context === "reading"
          ? "читать — круто"
          : "на пути к цели";

    if (phase === "welcome") {
      return { text: pickAvoidRepeat(P.welcome, prevText), tag: tag, voice: "" };
    }
    if (phase === "checked") {
      if (pct >= 100) {
        return {
          text: pickAvoidRepeat(P.perfect, prevText),
          tag:
            st.context === "listening-tfns"
              ? "TFNS · 100%"
              : st.context === "listening-mc"
                ? "MC · 100%"
              : st.context === "listening"
                ? "слух · 100%"
                : st.context === "reading"
                  ? "чтение · 100%"
                  : "100 баллов",
          voice: ""
        };
      }
      if (pct >= 80) {
        return {
          text: pickAvoidRepeat(P.excellent, prevText),
          tag:
            st.context === "listening-tfns" || st.context === "listening-mc" || st.context === "listening"
              ? "сильный слух"
              : st.context === "reading"
                ? "сильное чтение"
                : "уровень топ-балла",
          voice: ""
        };
      }
      if (pct >= 60) {
        return {
          text: pickAvoidRepeat(P.good, prevText),
          tag:
            st.context === "listening-tfns" || st.context === "listening-mc" || st.context === "listening"
              ? "слух растёт"
              : st.context === "reading"
                ? "чтение растёт"
                : "ты растёшь",
          voice: ""
        };
      }
      return pickRebuild(st, prevText);
    }
    if (total > 0 && filled >= total) {
      return {
        text: pickAvoidRepeat(P.progressFull, prevText),
        tag:
          st.context === "listening-tfns"
            ? "готово · A–G"
            : st.context === "listening-mc"
              ? "готово · 3–9"
            : st.context === "listening"
              ? "готово · проверка"
              : "готово к проверке",
        voice: ""
      };
    }
    if (total > 0 && filled >= total - 1 && filled > 0) {
      return {
        text: pickAvoidRepeat(P.progressAlmost, prevText),
        tag:
          st.context === "listening-tfns"
            ? "почти все A–G"
            : st.context === "listening-mc"
              ? "почти все 3–9"
            : st.context === "listening"
              ? "почти все спикеры"
              : "почти финиш",
        voice: ""
      };
    }
    if (total > 0 && filled >= Math.ceil(total / 2)) {
      return {
        text: pickAvoidRepeat(P.progressHalf, prevText),
        tag:
          st.context === "listening-tfns"
            ? "половина A–G"
            : st.context === "listening-mc"
              ? "половина 3–9"
            : st.context === "listening"
              ? "половина спикеров"
              : "полпути",
        voice: ""
      };
    }
    if (filled > 0) {
      return {
        text: pickAvoidRepeat(P.progressFew, prevText),
        tag:
          st.context === "listening-tfns" || st.context === "listening-mc" || st.context === "listening"
            ? "ухо проснулось"
            : "идём дальше",
        voice: ""
      };
    }
    return { text: pickAvoidRepeat(P.steady, prevText), tag: tag, voice: "" };
  }

  function applyCheerClasses(root, st, next) {
    var pct = st && st.percent != null ? st.percent : 0;
    var checked = st && st.phase === "checked";
    root.classList.toggle("ege-gx-cheer--perfect", checked && pct >= 100);
    root.classList.toggle(
      "ege-gx-cheer--excellent",
      checked && pct >= 80 && pct < 100
    );
    root.classList.toggle(
      "ege-gx-cheer--warm",
      checked && pct >= 60 && pct < 80
    );
    root.classList.toggle("ege-gx-cheer--rebuild", checked && pct < 60);
    root.classList.toggle(
      "ege-gx-cheer--legend",
      checked && pct < 60 && next && next.voice && next.voice !== "heart"
    );
    root.classList.toggle("ege-gx-cheer--legend-tyson", next && next.voice === "tyson");
    root.classList.toggle("ege-gx-cheer--legend-jobs", next && next.voice === "jobs");
    root.classList.toggle("ege-gx-cheer--heart", next && next.voice === "heart");
  }

